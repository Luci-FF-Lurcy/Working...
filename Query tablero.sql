            UNION ALL
            SELECT FECHA_ALTA,ID_ORDEN_TRABAJO,'KIOSKO' AS CANAL, FECHA_INGRESO, SUBSCRIBER_ID, IDENTIFICACION_CLIENTE, SUBPRODUCTO_HOMOLOGADO_FINAL,TECNOLOGIA_FINAL1,CATEGORIZACION_OPERACIONAL_N1,CATEGORIZACION_OPERACIONAL_N2, CATEGORIZACION_OPERACIONAL_N3,
                   REGION,CATEGORIA_RESOLUCION_NIVEL_1, TIPOLOGIA_GESTION,CATEGORIA_RESOLUCION_NIVEL_3,FECHA_IMPACTO,NFILAF, NULL AS RNR,NULL AS GRUPO_SOPORTE_ASIGNADOF
            FROM sandbox.SAC_RET.FIJO_INTENCIONES_KIOSKO 
            WHERE NFILAF = 1

            UNION ALL
            SELECT FECHA_ALTA,ID_ORDEN_TRABAJO,'INBOUND' AS CANAL,FECHA_CREACION, ID_SERVICIO,IDENTIFICACION, FAMILIA_FINAL,TECNOLOGIA_FINAL,CATEGORIZACION_OPERACIONAL_N1,CATEGORIZACION_OPERACIONAL_N2, CATEGORIZACION_OPERACIONAL_N3,
                   REGION,CATEGORIA_RESOLUCION_NIVEL_1,CATEGORIA_RESOLUCION_NIVEL_2_F,CATEGORIA_RESOLUCION_NIVEL_3,FECHA_IMPACTO,NFILAF, 
